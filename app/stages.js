  const COLS = 13;
  function placeItems(rows, list) {
    const out = rows.map((r) => r.padEnd(COLS, '.'));
    const hide = {};
    (list || []).forEach((spec) => {
      const m = /^(.)([@#])(\d+),(\d+)$/.exec(spec);
      if (!m) throw new Error('アイテムの 書きかたが ちがう: ' + spec);
      const [, code, how, rs, cs] = m;
      const r = Number(rs);
      const c = Number(cs);
      while (out.length <= r) out.push('.'.repeat(COLS));
      const cell = out[r][c];
      if (how === '@') {
        if (cell !== '.') throw new Error(spec + ' の マスが 空いて いない（' + cell + '）');
        out[r] = out[r].slice(0, c) + code + out[r].slice(c + 1);
      } else {
        if (!/[WHR]/.test(cell)) throw new Error(spec + ' の マスに ブロックが ない（' + cell + '）');
        hide[r + ',' + c] = code;
      }
    });
    return { rows: out, hide };
  }

